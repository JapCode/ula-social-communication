/**
 * Generates tina/generated-router.ts — a literal router map
 * built from the src/content/pages/ directory and routeMap.ts.
 *
 * Run: node scripts/build-router-map.mjs
 * Called automatically before `tinacms dev` and `tinacms build`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = join(fileURLToPath(import.meta.url), '..');
const ROOT = join(__dirname, '..');

// ── Read routeMap.ts to extract the getPageRoute logic ──────────
// We inline a minimal version so we don't need to parse TS at build time.
const routeMapRaw = readFileSync(join(ROOT, 'src/lib/routeMap.ts'), 'utf-8');

// Extract the pages2route object using a simple heuristic
const match = routeMapRaw.match(/pages2route\s*:\s*Record<string,\s*string>\s*=\s*(\{[\s\S]*?\});/);
const customRoutes = {};
if (match) {
  // Match 'program-index': '/program' (quoted keys) and home: '/' (unquoted keys)
  for (const m of match[1].matchAll(/('([^']+)'|(\w+))\s*:\s*'([^']+)'/g)) {
    const key = m[2] ?? m[3];  // group 2 = quoted key (without quotes), group 3 = unquoted key
    customRoutes[key] = m[4];  // group 4 = URL value
  }
}

function getPageRoute(filename) {
  return customRoutes[filename] ?? `/${filename}`;
}

// ── Read pages directory ──────────────────────────────────────
const pagesDir = join(ROOT, 'src/content/pages');
const files = readdirSync(pagesDir).filter(f => f.endsWith('.md'));

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const lines = match[1].split('\n');
  const data = {};
  let currentKey = null;
  for (const line of lines) {
    const kvMatch = line.match(/^(\w+):\s*(.*)/);
    if (kvMatch) {
      currentKey = kvMatch[1];
      data[currentKey] = kvMatch[2].replace(/^['"]|['"]$/g, '').trim();
    } else if (currentKey && line.startsWith('  ')) {
      // multi-line value (indented) — ignore for slug purposes
    }
  }
  return data;
}

const map = {};
for (const file of files) {
  const filename = file.replace(/\.md$/, '');
  const content = readFileSync(join(pagesDir, file), 'utf-8');
  const frontmatter = parseFrontmatter(content);
  // Use slug from frontmatter if present; normalize to start with /
  // otherwise fall back to routeMap logic
  let route = frontmatter.slug;
  if (route) {
    route = route.startsWith('/') ? route : `/${route}`;
  } else {
    route = getPageRoute(filename);
  }
  map[filename] = route;
}

// ── Build reverse map: route → filename (for catch-all) ────────
const reverseMap = {};
for (const [filename, route] of Object.entries(map)) {
  reverseMap[route] = filename;
}
// Also add entries from customRoutes that might not be in pages/ directory yet
for (const [filename, route] of Object.entries(customRoutes)) {
  if (!reverseMap[route]) {
    reverseMap[route] = filename;
  }
}

// ── Write generated TypeScript file ────────────────────────────
const ts = `// AUTO-GENERATED by scripts/build-router-map.mjs — DO NOT EDIT
// Run \`node scripts/build-router-map.mjs\` to regenerate when pages change.
export const routerMap: Record<string, string> = ${JSON.stringify(map, null, 2)};

/** Reverse map: URL route → page filename (includes custom slugs from frontmatter) */
export const slugMap: Record<string, string> = ${JSON.stringify(reverseMap, null, 2)};
`;

writeFileSync(join(ROOT, 'tina/generated-router.ts'), ts, 'utf-8');
console.log(`✅ Generated tina/generated-router.ts — ${Object.keys(map).length} routes, ${Object.keys(reverseMap).length} reverse entries`);
